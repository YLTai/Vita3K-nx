#!/usr/bin/env python3
"""Compile and validate the PRIVATE BDA probe; never compile shader source on device.

Requires host glslangValidator and spirv-val/spirv-dis. Output is a generated
header plus a manifest identifying the actual compiler, GLSL and SPIR-V.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'vita3k/renderer/shaders/switch_mirror_probe.comp'

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output-dir', type=Path, required=True)
    args = p.parse_args()
    tools = {n: shutil.which(n) for n in ('glslangValidator', 'spirv-val', 'spirv-dis')}
    missing = [n for n, v in tools.items() if not v]
    if missing:
        raise SystemExit('Missing host shader tools: ' + ', '.join(missing)
                         + '; install glslang-tools and spirv-tools')
    with tempfile.TemporaryDirectory() as t:
        binary = Path(t) / 'mirror.spv'
        subprocess.run([tools['glslangValidator'], '-V', '--target-env', 'vulkan1.1',
                        '-o', str(binary), str(SOURCE)], check=True)
        subprocess.run([tools['spirv-val'], '--target-env', 'vulkan1.1', str(binary)], check=True)
        dis = subprocess.run([tools['spirv-dis'], str(binary)], check=True,
                             text=True, capture_output=True).stdout
        # A64 host pointers do not imply that shaderInt64 was enabled. This
        # shader carries physical pointers directly, not 64-bit arithmetic.
        assert 'OpCapability PhysicalStorageBufferAddresses' in dis
        assert 'PhysicalStorageBuffer64' in dis
        assert re.search(r'OpExecutionMode\s+%\w+\s+LocalSize\s+64\s+1\s+1', dis)
        # Verify the generated shader contract, not merely the C++ struct.
        layouts = {}
        for block, member, offset in re.findall(r'OpMemberDecorate\s+(%\w+)\s+(\d+)\s+Offset\s+(\d+)', dis):
            layouts.setdefault(block, {})[int(member)] = int(offset)
        expected_layout = dict(enumerate((0, 8, 16, 20, 24, 28)))
        assert expected_layout in layouts.values(), 'SPIR-V push layout differs from C++ ABI'
        assert 'OpCapability Int64' not in dis and 'DescriptorSet' not in dis
        data = binary.read_bytes()
        assert len(data) % 4 == 0 and struct.unpack_from('<I', data)[0] == 0x07230203
        words = struct.unpack('<' + 'I' * (len(data) // 4), data)
        assert words[1] == 0x00010300, 'Expected exactly SPIR-V 1.3'
        source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
        binary_hash = hashlib.sha256(data).hexdigest()
        lines = ['// Generated by build-switch-mirror-shader.py; do not edit.', '#pragma once',
                 '#include <cstdint>', 'namespace switch_validation::mirror_shader {',
                 f'inline constexpr char source_sha256[] = "{source_hash}";',
                 f'inline constexpr char spirv_sha256[] = "{binary_hash}";',
                 'inline constexpr uint32_t spirv[] = {']
        lines += ['    ' + ', '.join(f'0x{w:08x}' for w in words[i:i+8]) + ','
                  for i in range(0, len(words), 8)]
        lines += ['};', '} // namespace switch_validation::mirror_shader', '']
        args.output_dir.mkdir(parents=True, exist_ok=True)
        def publish(name, content):
            path = args.output_dir / name
            if not path.exists() or path.read_bytes() != content:
                tmp = path.with_suffix(path.suffix + '.tmp')
                tmp.write_bytes(content)
                tmp.replace(path)
        publish('switch_mirror_shader_spv.h', '\n'.join(lines).encode())
        publish('switch_mirror_shader.spv', data)
        publish('switch_mirror_shader.spvasm', dis.encode())
        manifest = dict(source_sha256=source_hash, spirv_sha256=binary_hash,
                        target='vulkan1.1 / SPIR-V 1.3 + SPV_KHR_physical_storage_buffer',
                        compiler=subprocess.run([tools['glslangValidator'], '--version'], check=True,
                                                text=True, capture_output=True).stdout,
                        validated=True, shader_int64_required=False,
                        local_size=[64, 1, 1], push_member_offsets=[0, 8, 16, 20, 24, 28])
        publish('manifest.json', (json.dumps(manifest, indent=2)+'\n').encode())
    print('Private BDA shader compiled and validated; no GPU execution is implied')

if __name__ == '__main__':
    main()
